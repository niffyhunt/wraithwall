# ── deterministic PRNG (xorshift32 keyed by ASCII string) ────────────────────


def _key_u32(key: str) -> int:
    digest = hashlib.sha256(key.encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big") or 0x9E3779B9  # never zero


class _Xs:
    """Tiny deterministic PRNG. Same key string ⇒ same byte stream anywhere."""

    __slots__ = ("s",)

    def __init__(self, key: str) -> None:
        self.s = _key_u32(key)
        for _ in range(4):  # decorrelate related keys
            self.next()

    def next(self) -> int:
        s = self.s
        s ^= (s << 13) & 0xFFFFFFFF
        s ^= s >> 17
        s ^= (s << 5) & 0xFFFFFFFF
        self.s = s or 0x9E3779B9
        return self.s

    def below(self, n: int) -> int:
        return self.next() % n

    def pick(self, seq: Tuple[str, ...]) -> str:
        return seq[self.below(len(seq))]

    def shuffle(self, items: List[Any]) -> None:
        for i in range(len(items) - 1, 0, -1):
            j = self.below(i + 1)
            items[i], items[j] = items[j], items[i]


