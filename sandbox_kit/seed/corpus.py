# ── record builders ──────────────────────────────────────────────────────────


def _iso(ts: int) -> str:
    # Deterministic ISO-8601 (UTC, Z suffix) without importing datetime at
    # module scope — same output on every platform.
    days, rem = divmod(ts, 86400)
    hh, rem = divmod(rem, 3600)
    mm, ss = divmod(rem, 60)
    # Civil-from-days (Howard Hinnant's algorithm), proleptic Gregorian.
    z = days + 719468
    era = z // 146097
    doe = z - era * 146097
    yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    y = yoe + era * 400
    doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    mp = (5 * doy + 2) // 153
    d = doy - (153 * mp + 2) // 5 + 1
    m = mp + 3 if mp < 10 else mp - 9
    y = y + (1 if m <= 2 else 0)
    return "%04d-%02d-%02dT%02d:%02d:%02d.%06dZ" % (y, m, d, hh, mm, ss, 0)


