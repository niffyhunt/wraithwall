"""Deterministic synthetic Cowrie session corpus (Phase 4).

Design contract (from LOCAL_SANDBOX_MVP_SPECIFICATION.md and the Stage 2
data policy):

- **Fixed seed**: byte-identical output for a given ``seed_version`` on any
  machine, any date. There is no wall-clock and no OS entropy in the corpus:
  every random choice comes from a tiny xorshift PRNG keyed by an ASCII seed
  string, and every timestamp derives from one fixed epoch offset.
- **LOCAL marking**: every record carries ``"sandbox": "LOCAL"`` and a sensor
  name of ``ww-sandbox-local`` so no synthetic record can ever be mistaken for
  production telemetry (Stage 2 provenance requirement).
- **No real credentials**: every secret-shaped string is repo-canonically fake
  (the ``_SANDBOX_FAKE_*`` convention) and additionally IP-ranged into
  RFC 5737 documentation space (192.0.2.0/24) — nothing routable.
- **Hostile-string corpus**: a deterministic slice of sessions carries
  injection-attempt strings (prompt-injection phrasings, template/SQL payloads,
  shell metacharacters). G12's property holds by construction *and* is tested
  end-to-end: these strings are DATA inside JSON records and must never become
  instructions anywhere downstream (``[[SEED_INJECTION_TEST_{n}]]`` markers
  make any leak greppable).
- **Pipeline-complete**: event shapes match exactly what
  ``cowrie_intelligence.CowrieIntelligencePipeline._handle_event`` dispatches
  on (the six handled eventids) and what its handlers read
  (``transport``/hassh arrays, ``username``/``password``, ``input``,
  ``url``/``outfile``, ``duration``), so the unchanged pipeline produces
  sessions, campaigns, deception-bus bait hits and MITRE mappings.
"""

