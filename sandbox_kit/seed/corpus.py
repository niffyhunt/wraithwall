#: Cowrie ttylog frame header (cowrie 3.0.14 src/cowrie/core/ttylog.py):
#: ``<iLiiLL`` = [op][tty][length][direction][sec][usec], little-endian.
_TTY_HDR = struct.Struct("<iLiiLL")
_TTY_OP_OPEN, _TTY_OP_WRITE = 1, 3
_TTY_DIR_INPUT, _TTY_DIR_OUTPUT = 1, 2


def tty_frames(seed_version: str = SEED_VERSION,
               sids: Iterable[str] | None = None) -> List[Tuple[str, bytes]]:
    """Deterministic binary ttylog content per session id.

    Returns ``(session_id, ttylog_bytes)`` where the bytes are real Cowrie
    ttylog frames — the format ``wraithwall.replay_tty.parse_ttylog`` reads:
    a 24-byte little-endian ``<iLiiLL`` header per frame followed by
    ``length`` payload bytes.

    Each session opens once (``op=1``), writes its synthetic script as
    ``op=3`` frames, and mixes attacker INPUT (``direction=1``) with the
    honeypot's own OUTPUT (``direction=2``) so replay exercises the same
    "input frames only" filter real Cowrie logs hit. Timestamps are small
    offsets from EPOCH_BASE so replay timing is stable.
    """
    if sids is None:
        sids = session_ids("corpus|" + seed_version, 24)
    out: List[Tuple[str, bytes]] = []
    for idx, sid in enumerate(sids):
        rng = _Xs("tty|%s|%d" % (seed_version, idx))
        lines = list(_TTY_SCRIPTS[idx % len(_TTY_SCRIPTS)])
        rng.shuffle(lines)
        t0 = EPOCH_BASE + idx * 37
        buf = bytearray()
        buf += _TTY_HDR.pack(_TTY_OP_OPEN, 0, 0, _TTY_DIR_INPUT,
                             t0, 0)
        for i, line in enumerate(lines):
            data = line.encode("utf-8")
            # every 4th line is the honeypot's own output; the rest is input
            direction = _TTY_DIR_OUTPUT if i % 4 == 3 else _TTY_DIR_INPUT
            buf += _TTY_HDR.pack(_TTY_OP_WRITE, 0, len(data), direction,
                                 t0 + i * 3, 0)
            buf += data
        out.append((sid, bytes(buf)))
    return out
