def session_ids(rng_seed: str, count: int) -> List[str]:
    """Deterministic, unique session ids for a corpus version."""
    rng = _Xs("sids|" + rng_seed)
    out: List[str] = []
    seen = set()
    while len(out) < count:
        # Two draws = 64 bits, so ids are not trivially zero-prefixed.
        sid = "%016x" % ((rng.next() << 32) | rng.next())
        if sid not in seen:
            seen.add(sid)
            out.append(sid)
    return out


# Session archetype plan (deterministic mix, 24 sessions):
#   0-7    recon + failed logins then success, commands
#   8-13   bait-reading operators (HoneyFS deception-bus hits)
#   14-17  credential stuffing bursts (VANISH / cred-storm)
#   18-20  hostile-string carriers (G12)
#   21-23  downloads + persistence, long sessions
_ARCHETYPE_PLAN: Tuple[int, ...] = (
    (0,) * 8 + (1,) * 6 + (2,) * 4 + (3,) * 3 + (7,) * 3
)


def build_sessions(seed_version: str = SEED_VERSION) -> List[Dict[str, Any]]:
    """Return the full deterministic session list (as event dicts, in the
    exact order they must be written). The output is a pure function of
    ``seed_version``."""
    rng_seed = "corpus|" + seed_version
    sids = session_ids(rng_seed, 24)
    sessions: List[Dict[str, Any]] = []

    for idx, sid in enumerate(sids):
        rng = _Xs("session|%s|%d" % (seed_version, idx))
        src_ip = SOURCE_IPS[rng.below(len(SOURCE_IPS))]
        transport = TRANSPORTS[idx % len(TRANSPORTS)]
        t0 = EPOCH_BASE + idx * 937 + rng.below(300)

        archetype = _ARCHETYPE_PLAN[idx]
        events: List[Dict[str, Any]] = []

        events.append({
            "eventid": "cowrie.session.connect",
            "session": sid,
            "src_ip": src_ip,
            "src_port": 30000 + rng.below(20000),
            "dst_ip": "172.18.0.10",
            "dst_port": 22,
            "protocol": "tcp",
            "timestamp": _iso(t0),
            "sensor": LOCAL_SENSOR,
            "sandbox": LOCAL_MARK,
            "transport": dict(transport),
        })

        # ── logins ────────────────────────────────────────────────────────
        n_fail = 0 if archetype == 3 else 1 + rng.below(6)
        attempts = []
        for i in range(n_fail):
            attempts.append({
                "eventid": "cowrie.login.failed",
                "session": sid,
                "src_ip": src_ip,
                "username": rng.pick(USERS),
                "password": rng.pick(PASSWORDS),
                "timestamp": _iso(t0 + 3 + i * 2),
                "sensor": LOCAL_SENSOR,
                "sandbox": LOCAL_MARK,
            })
        success_user = rng.pick(USERS)
        attempts.append({
            "eventid": "cowrie.login.success",
            "session": sid,
            "src_ip": src_ip,
            "username": success_user,
            "password": rng.pick(PASSWORDS),
            "timestamp": _iso(t0 + 3 + n_fail * 2 + 1),
            "sensor": LOCAL_SENSOR,
            "sandbox": LOCAL_MARK,
        })
        if archetype == 2:  # stuffing burst: many more failures
            for i in range(14):
                attempts.append({
                    "eventid": "cowrie.login.failed",
                    "session": sid,
                    "src_ip": src_ip,
                    "username": "user%02d" % (rng.below(40)),
                    "password": rng.pick(PASSWORDS),
                    "timestamp": _iso(t0 + 40 + i),
                    "sensor": LOCAL_SENSOR,
                    "sandbox": LOCAL_MARK,
                })
        events.extend(attempts)

        # ── commands ──────────────────────────────────────────────────────
        cmds: List[str] = []
        if archetype == 0:
            cmds = [rng.pick(RECON_COMMANDS) for _ in range(3 + rng.below(5))]
        elif archetype == 1:
            cmds = [rng.pick(BAIT_COMMANDS) for _ in range(2 + rng.below(4))]
            cmds.append(rng.pick(RECON_COMMANDS))
        elif archetype == 2:
            cmds = ["uname -a", "cat /etc/shadow", rng.pick(RECON_COMMANDS)]
        elif archetype == 3:
            cmds = [rng.pick(INJECTION_STRINGS) for _ in range(2 + rng.below(2))]
        else:
            cmds = ([rng.pick(RECON_COMMANDS)]
                    + [rng.pick(BAIT_COMMANDS) for _ in range(rng.below(2) + 1)]
                    + [rng.pick(TOOL_COMMANDS) for _ in range(rng.below(2) + 1)])

        last_cmd_ts = t0 + 20
        for i, cmd in enumerate(cmds):
            last_cmd_ts = t0 + 25 + i * (2 + rng.below(6))
            events.append({
                "eventid": "cowrie.command.input",
                "session": sid,
                "src_ip": src_ip,
                "input": cmd,
                "timestamp": _iso(last_cmd_ts),
                "sensor": LOCAL_SENSOR,
                "sandbox": LOCAL_MARK,
            })

        # ── downloads (long/persistence sessions) ─────────────────────────
        if archetype == 7:
            for i in range(1 + rng.below(2)):
                events.append({
                    "eventid": "cowrie.session.file_download",
                    "session": sid,
                    "src_ip": src_ip,
                    "url": DOWNLOAD_URLS[rng.below(len(DOWNLOAD_URLS))],
                    "outfile": DOWNLOAD_OUTFILES[rng.below(len(DOWNLOAD_OUTFILES))],
                    "timestamp": _iso(last_cmd_ts + 5 + i * 7),
                    "sensor": LOCAL_SENSOR,
                    "sandbox": LOCAL_MARK,
                })

        # ── close ─────────────────────────────────────────────────────────
        duration = (last_cmd_ts - t0) + 30 + rng.below(600)
        events.append({
            "eventid": "cowrie.session.closed",
            "session": sid,
            "src_ip": src_ip,
            "duration": duration,
            "timestamp": _iso(t0 + duration),
            "sensor": LOCAL_SENSOR,
            "sandbox": LOCAL_MARK,
        })

        sessions.append(events)

    return sessions


# ── serialization ────────────────────────────────────────────────────────────


def event_lines(seed_version: str = SEED_VERSION) -> List[str]:
    """The corpus as JSONL lines (one JSON object per line, stable key order)."""
    lines: List[str] = []
    for events in build_sessions(seed_version):
        for ev in events:
            lines.append(json.dumps(ev, sort_keys=True, separators=(",", ":")))
    return lines


def corpus_digest(seed_version: str = SEED_VERSION) -> str:
    """SHA-256 over the exact byte stream the seed writes (newline-joined).

    Two deployments that agree on ``seed_version`` must produce the same
    digest; the shipper self-checks against this before shipping.
    """
    payload = ("\n".join(event_lines(seed_version)) + "\n").encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def record_count(seed_version: str = SEED_VERSION) -> int:
    return len(event_lines(seed_version))


